"""Modal cloud backend integration.

This module provides a complete deployment definition for running the video generation
pipeline on Modal GPU instances (e.g. L4, A100, or H100) whenever needed in the future.

Usage:
    modal run video_gen/backends/modal_runner.py --prompt "cinematic flyover" --duration 10
    modal deploy video_gen/backends/modal_runner.py
"""

import os
from pathlib import Path
from typing import Any, Dict, List, Optional

try:
    import modal
    MODAL_AVAILABLE = True
except ImportError:
    MODAL_AVAILABLE = False


if MODAL_AVAILABLE:
    # Define remote container environment
    video_gen_image = (
        modal.Image.debian_slim(python_version="3.11")
        .apt_install("ffmpeg", "git")
        .pip_install(
            "torch>=2.0.0",
            "diffusers>=0.28.0",
            "transformers>=4.38.0",
            "accelerate>=0.28.0",
            "fastapi>=0.100.0",
            "uvicorn>=0.20.0",
            "pydantic>=2.0.0",
            "pillow>=9.0.0",
            "numpy>=1.22.0",
            "requests>=2.28.0",
            "imageio>=2.30.0",
            "imageio-ffmpeg>=0.4.8",
            "python-multipart>=0.0.6",
        )
        .add_local_python_source("video_gen")
    )

    app = modal.App("video-generation-prototype", image=video_gen_image)

    # Persistent volume for caching model weights and generated videos
    cache_volume = modal.Volume.from_name("svd-model-cache", create_if_missing=True)

    @app.cls(
        gpu="L4",
        timeout=1800,
        volumes={"/root/.cache/huggingface": cache_volume},
        scaledown_window=300,
    )
    class ModalVideoService:
        """Remote GPU worker running on Modal."""

        @modal.enter()
        def setup(self):
            from video_gen.config import VideoConfig
            from video_gen.generator import LongVideoGenerator

            self.config = VideoConfig.for_modal(duration_seconds=10.0, gpu_type="L4")
            self.generator = LongVideoGenerator(config=self.config)
            # Preload pipeline onto GPU
            self.generator.pipeline.load()

        @modal.method()
        def generate_video(
            self,
            prompt: Optional[str] = None,
            image_url: Optional[str] = None,
            duration_seconds: float = 10.0,
            fps: int = 7,
            motion_bucket_id: Optional[int] = None,
            num_inference_steps: int = 25,
            seed: Optional[int] = None,
        ) -> Dict[str, Any]:
            """Execute video generation on remote Modal L4 GPU."""
            result = self.generator.generate(
                prompt=prompt,
                image=image_url,
                duration_seconds=duration_seconds,
                fps=fps,
                motion_bucket_id=motion_bucket_id,
                num_inference_steps=num_inference_steps,
                seed=seed,
            )

            # Read generated bytes to return
            video_bytes = result.video_path.read_bytes()
            return {
                "video_bytes": video_bytes,
                "metadata": result.metadata,
                "duration_seconds": result.duration_seconds,
                "fps": result.fps,
                "num_frames": result.num_frames,
            }

    @app.local_entrypoint()
    def main(
        prompt: str = "Cinematic aerial camera gliding smoothly over majestic natural scenery, sunset lighting",
        image: Optional[str] = None,
        duration: float = 10.0,
        output: str = "modal_output.mp4",
    ):
        """CLI local entrypoint for `modal run`."""
        print(f"Submitting video generation to Modal L4 GPU (duration={duration}s)...")
        service = ModalVideoService()
        res = service.generate_video.remote(
            prompt=prompt,
            image_url=image,
            duration_seconds=duration,
        )
        out_file = Path(output)
        out_file.write_bytes(res["video_bytes"])
        print(f"Done! Remote video saved to: {out_file.resolve()}")

else:
    # Stub when modal package is not installed locally
    class ModalVideoService:  # type: ignore
        def __init__(self, *args, **kwargs):
            raise ImportError(
                "Modal is not installed. To use the Modal backend in the future, "
                "run: pip install modal && modal setup"
            )
